export function findCatalogMatch(
  productId?: string,
  brand?: string,
  name?: string
): CatalogProduct | undefined {
  if (productId) {
    const byId = PRODUCT_CATALOG.find((p) => p.id === productId);
    if (byId) return byId;
  }
  const cleanName = (name || "").trim().toLowerCase();
  const cleanBrand = (brand || "").trim().toLowerCase();
  if (!cleanName) return undefined;

  return PRODUCT_CATALOG.find(
    (p) =>
      cleanName.includes(p.name.toLowerCase()) ||
      (cleanBrand &&
        p.brand.toLowerCase().includes(cleanBrand) &&
        cleanName.includes(p.name.split(" ")[0].toLowerCase()))
  );
}

export function getAuthenticBuyUrl(
  brand: string,
  name: string,
  productId?: string
): string {
  const verifiedUrl = getVerifiedAffiliateUrl({ brand, name, productId });
  if (verifiedUrl) return verifiedUrl;
  const catalogHit = findCatalogMatch(productId, brand, name);
  const url = catalogHit?.affiliateUrl?.trim() || "";
  return url;
}

